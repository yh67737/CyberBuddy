#!/usr/bin/env python3
"""
Import security violation entries into Milvus for RAG retrieval.

Reads ``data/security_violations.json`` (generated by
``extract_violations.py``), expands each entry's ``example_phrases`` into
individual rows, and indexes them into the ``security_violations`` collection.

Each row:
  - phrase    = one example employee phrase  (this is what gets embedded)
  - violation = canonical violation name
  - severity  = critical / high / medium / low
  - category  = 数据泄露 / 账号密码 / 访问控制 / 异常行为 / 设备安全 / 其他

SecurityGuardian then searches this collection: when a user report matches a
phrase, the hit returns the violation name + severity to ground its judgement.

Usage:
    python scripts/import_violations.py              # index all phrases
    python scripts/import_violations.py --dry-run    # validate only, no insert
    python scripts/import_violations.py --stats      # show collection stats

Environment:
    MILVUS_HOST  — Milvus server host (default: localhost)
    MILVUS_PORT  — Milvus gRPC port  (default: 19530)
"""

import argparse
import json
import os
import sys
import time
from pathlib import Path

sys.stdout.reconfigure(line_buffering=True)

# ── Constants ────────────────────────────────────────────────────────
PROJECT_ROOT = Path(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INPUT_FILE = PROJECT_ROOT / "data" / "security_violations.json"
COLLECTION_NAME = "security_violations"
MAX_VARCHAR = 65535
CONNECTION_ALIAS = "cyberbuddy_violations_import"


def load_phrases() -> list[dict]:
    """Expand entries into per-phrase rows."""
    if not INPUT_FILE.exists():
        print(f"❌ Missing input file: {INPUT_FILE}")
        sys.exit(1)

    data = json.loads(INPUT_FILE.read_text(encoding="utf-8"))
    rows = []
    seen = set()

    for entry in data:
        violation = str(entry.get("violation", "")).strip()
        severity = str(entry.get("severity", "medium")).strip()
        category = str(entry.get("category", "其他")).strip()
        if not violation:
            continue

        for phrase in entry.get("example_phrases", []):
            phrase = str(phrase).strip()
            if not phrase:
                continue
            key = phrase.lower()
            if key in seen:
                continue
            seen.add(key)
            rows.append({
                "phrase": phrase,
                "violation": violation,
                "severity": severity,
                "category": category,
            })

    return rows


def connect_milvus(host: str, port: int, drop_existing: bool = False):
    """Connect and ensure the violations collection exists."""
    from pymilvus import (
        Collection,
        CollectionSchema,
        connections,
        DataType,
        FieldSchema,
        utility,
    )

    if connections.has_connection(CONNECTION_ALIAS):
        return

    connections.connect(alias=CONNECTION_ALIAS, host=host, port=port)
    print(f"🔗 Connected to Milvus at {host}:{port}")

    if utility.has_collection(COLLECTION_NAME, using=CONNECTION_ALIAS):
        if drop_existing:
            utility.drop_collection(COLLECTION_NAME, using=CONNECTION_ALIAS)
            print("🗑️  Dropped existing collection (will recreate)")
        else:
            col = Collection(COLLECTION_NAME, using=CONNECTION_ALIAS)
            col.load()
            print(f"📦 Collection '{COLLECTION_NAME}' exists: {col.num_entities:,} entities")
            return col

    fields = [
        FieldSchema(name="id", dtype=DataType.INT64, is_primary=True, auto_id=True),
        FieldSchema(name="embedding", dtype=DataType.FLOAT_VECTOR, dim=1024),
        FieldSchema(name="phrase", dtype=DataType.VARCHAR, max_length=MAX_VARCHAR),
        FieldSchema(name="violation", dtype=DataType.VARCHAR, max_length=MAX_VARCHAR),
        FieldSchema(name="severity", dtype=DataType.VARCHAR, max_length=32),
        FieldSchema(name="category", dtype=DataType.VARCHAR, max_length=32),
    ]
    schema = CollectionSchema(fields, description="安全违规条目库 (示例提问 → 违规名称 + 风险等级)")
    col = Collection(COLLECTION_NAME, schema=schema, using=CONNECTION_ALIAS)

    index_params = {
        "metric_type": "COSINE",
        "index_type": "IVF_FLAT",
        "params": {"nlist": 128},
    }
    col.create_index(field_name="embedding", index_params=index_params)
    col.load()
    print(f"📦 Created collection '{COLLECTION_NAME}' with IVF_FLAT/COSINE")
    return col


def show_stats(host: str, port: int) -> None:
    from pymilvus import Collection, connections, utility

    if not connections.has_connection(CONNECTION_ALIAS):
        connections.connect(alias=CONNECTION_ALIAS, host=host, port=port)
    if not utility.has_collection(COLLECTION_NAME, using=CONNECTION_ALIAS):
        print(f"Collection '{COLLECTION_NAME}' does not exist yet.")
        return
    col = Collection(COLLECTION_NAME, using=CONNECTION_ALIAS)
    col.load()
    print(f"\n📊 Collection: {COLLECTION_NAME}")
    print(f"   Entities:   {col.num_entities:,}")
    print(f"   Loaded:     {'yes' if col.is_loaded else 'no'}")


def main():
    parser = argparse.ArgumentParser(description="Import security violations into Milvus")
    parser.add_argument("--dry-run", action="store_true", help="Validate only, no insert")
    parser.add_argument("--stats", action="store_true", help="Show collection stats and exit")
    parser.add_argument("--drop", action="store_true", help="Drop & recreate existing collection")
    parser.add_argument("--host", type=str, default=None)
    parser.add_argument("--port", type=int, default=None)
    parser.add_argument("--model", type=str, default="BAAI/bge-large-zh-v1.5")
    args = parser.parse_args()

    host = args.host or os.environ.get("MILVUS_HOST", "localhost")
    port = args.port or int(os.environ.get("MILVUS_PORT", "19530"))

    if args.stats:
        show_stats(host, port)
        return

    # ── Load data ────────────────────────────────────────────────────
    rows = load_phrases()
    print(f"📖 Loaded {len(rows)} phrases from {INPUT_FILE.name}")

    # Summary
    from collections import Counter
    sev = Counter(r["severity"] for r in rows)
    cat = Counter(r["category"] for r in rows)
    print("  severity:", dict(sorted(sev.items())))
    print("  category:", dict(sorted(cat.items(), key=lambda x: -x[1])))

    if not rows:
        print("❌ No phrases to index.")
        sys.exit(1)

    if args.dry_run:
        print("\n🔍 Dry run — sample phrases:")
        for r in rows[:5]:
            print(f"  [{r['severity']:8s}] {r['phrase']}  →  {r['violation']}")
        return

    # ── Load embedding model ─────────────────────────────────────────
    print(f"\n🧠 Loading embedding model: {args.model}")
    from sentence_transformers import SentenceTransformer

    model = SentenceTransformer(args.model)
    dim = model.get_sentence_embedding_dimension()
    print(f"  ✅ Model loaded (dim={dim})")

    # ── Connect Milvus ───────────────────────────────────────────────
    print(f"\n🔗 Connecting to Milvus")
    col = connect_milvus(host, port, drop_existing=args.drop)

    # ── Embed + insert ───────────────────────────────────────────────
    print(f"\n🚀 Indexing {len(rows)} phrases...")
    phrases = [r["phrase"] for r in rows]

    t_start = time.time()
    embeddings = model.encode(
        phrases,
        normalize_embeddings=True,
        show_progress_bar=False,
        batch_size=100,
    ).tolist()
    print(f"  ✅ Embedded {len(phrases)} phrases in {time.time() - t_start:.1f}s")

    entities = [
        embeddings,
        [r["phrase"] for r in rows],
        [r["violation"] for r in rows],
        [r["severity"] for r in rows],
        [r["category"] for r in rows],
    ]
    col.insert(entities)
    col.flush()

    print(f"\n{'=' * 60}")
    print(f"✅ Import complete!")
    print(f"   Collection:  {COLLECTION_NAME}")
    print(f"   Total rows:  {col.num_entities:,}")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    main()
